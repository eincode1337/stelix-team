import type { Metadata } from 'next'
import { DocumentLayout, DocSection } from '@/components/legal/DocumentLayout'
import { isLocale, type Locale } from '@/i18n/config'

const SITE = 'https://stelix.team'

export async function generateMetadata({ params }: { params: Promise<{ locale: string }> }): Promise<Metadata> {
  const { locale } = await params
  const loc: Locale = isLocale(locale) ? locale : 'ru'
  return {
    title: 'Политика лицензирования контента — Stelix Team',
    description: 'Виды лицензий, права покупателя, запреты; автор сохраняет права на контент.',
    alternates: {
      canonical: `/${loc}/licensing-policy`,
      languages: {
        ru: '/ru/licensing-policy',
        uk: '/uk/licensing-policy',
        en: '/en/licensing-policy',
        'x-default': `${SITE}/licensing-policy`,
      },
    },
  }
}

