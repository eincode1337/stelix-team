const SITE = 'https://stelix.team'

export async function generateMetadata({ params }: { params: Promise<{ locale: string }> }): Promise<Metadata> {
  const { locale } = await params
  const loc: Locale = isLocale(locale) ? locale : 'ru'
  return {
    title: 'Политика статусов и доступа — Stelix Team',
    description: 'Статусы и доступ; числовые пороги — в Условиях, раздел 10.',
    alternates: {
      canonical: `/${loc}/statuses-policy`,
      languages: {
        ru: '/ru/statuses-policy',
        uk: '/uk/statuses-policy',
        en: '/en/statuses-policy',
        'x-default': `${SITE}/statuses-policy`,
      },
    },
  }
}

