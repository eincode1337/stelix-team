const SITE = 'https://stelix.team'

export async function generateMetadata({ params }: { params: Promise<{ locale: string }> }): Promise<Metadata> {
  const { locale } = await params
  const loc: Locale = isLocale(locale) ? locale : 'ru'
  return {
    title: 'Оплата и доставка — Stelix Team',
    description: 'VISA, MasterCard, МИР, СБП; цифровая доставка мгновенно или по заявке; срок возврата до 30 рабочих дней.',
    alternates: {
      canonical: `/${loc}/payment-info`,
      languages: {
        ru: '/ru/payment-info',
        uk: '/uk/payment-info',
        en: '/en/payment-info',
        'x-default': `${SITE}/payment-info`,
      },
    },
  }
}

