import type { Metadata } from 'next'
import { DocumentLayout, DocSection } from '@/components/legal/DocumentLayout'
import { isLocale, type Locale } from '@/i18n/config'

const SITE = 'https://stelix.team'

export async function generateMetadata({ params }: { params: Promise<{ locale: string }> }): Promise<Metadata> {
  const { locale } = await params
  const loc: Locale = isLocale(locale) ? locale : 'ru'
  return {
    title: 'Политика офф-платформенных сделок — Stelix Team',
    description: 'Увод сделок с Площадки: запрет, доказательства, санкции.',
    alternates: {
      canonical: `/${loc}/offplatform-policy`,
      languages: {
        ru: '/ru/offplatform-policy',
        uk: '/uk/offplatform-policy',
        en: '/en/offplatform-policy',
        'x-default': `${SITE}/offplatform-policy`,
      },
    },
  }
}

