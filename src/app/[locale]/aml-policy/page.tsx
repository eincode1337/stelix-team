const SITE = 'https://stelix.team'

export async function generateMetadata({ params }: { params: Promise<{ locale: string }> }): Promise<Metadata> {
  const { locale } = await params
  const loc: Locale = isLocale(locale) ? locale : 'ru'
  return {
    title: 'AML и антифрод политика — Stelix Team',
    description: 'Заморозка, мониторинг, верификация, чарджбеки, запросы банков и ПС.',
    alternates: {
      canonical: `/${loc}/aml-policy`,
      languages: {
        ru: '/ru/aml-policy',
        uk: '/uk/aml-policy',
        en: '/en/aml-policy',
        'x-default': `${SITE}/aml-policy`,
      },
    },
  }
}

